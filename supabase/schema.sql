-- HangulMate cloud schema starter (run in Supabase SQL Editor)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  native_language text not null default 'English',
  xp integer not null default 0,
  streak integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.mistakes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  korean_word text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.mission_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mission_key text not null,
  completed_at timestamptz not null default now(),
  unique(user_id, mission_key)
);

alter table public.profiles enable row level security;
alter table public.mistakes enable row level security;
alter table public.mission_completions enable row level security;

create policy "Users can read own profile" on public.profiles
for select using (auth.uid() = id);
create policy "Users can insert own profile" on public.profiles
for insert with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles
for update using (auth.uid() = id);

create policy "Users can manage own mistakes" on public.mistakes
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can manage own mission completions" on public.mission_completions
for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Create a profile row automatically when a new Auth user signs up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', 'Learner'));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
